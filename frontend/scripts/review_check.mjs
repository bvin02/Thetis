import { chromium } from '@playwright/test'
const out = process.argv[2] ?? '../data/shots'
const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
const logs = []
page.on('console', (m) => { if (['error', 'warning'].includes(m.type())) logs.push(`[${m.type()}] ${m.text()}`) })
page.on('pageerror', (e) => logs.push(`[pageerror] ${e.message}`))
await page.goto('http://localhost:5173/checks/new?tank=T-03', { waitUntil: 'networkidle' })
await page.waitForTimeout(300)
await page.screenshot({ path: `${out}/nc-empty.png` })
await page.getByRole('button', { name: 'Use a sample slide' }).click()
await page.waitForTimeout(400)
await page.screenshot({ path: `${out}/nc-menu.png` })
await page.getByRole('menuitem', { name: /T-03 today/ }).click()
await page.locator('svg[role=application] polygon').first().waitFor()
await page.waitForTimeout(300)
await page.getByRole('button', { name: /Ignored/ }).click()
await page.waitForTimeout(200)
await page.screenshot({ path: `${out}/nc-ignored.png` })
const ignored = await page.evaluate(() => [...document.querySelectorAll('svg[role=application] polygon[stroke="#AEB9C0"]')].map((p) => {
  const b = p.getBoundingClientRect(); return [Math.round(b.x), Math.round(b.y), Math.round(b.width), Math.round(b.height)]
}))
console.log('ignored outlines (screen px):', JSON.stringify(ignored))
await page.getByRole('button', { name: /Ignored/ }).click()
await page.getByRole('button', { name: 'Review', exact: true }).click()
await page.waitForTimeout(350)
await page.screenshot({ path: `${out}/nc-zoom.png` })
console.log(JSON.stringify(logs))
await page.setViewportSize({ width: 390, height: 844 })
await page.waitForTimeout(400)
await page.screenshot({ path: `${out}/nc-phone.png`, fullPage: true })
const overflow = await page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth)
console.log('phone overflow', overflow)
await browser.close()
